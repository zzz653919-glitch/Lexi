const path = require('path');
const { pathToFileURL } = require('url');
let playwright;
try { playwright = require('playwright'); } catch (e) { playwright = require(require('child_process').execSync('npm root -g').toString().trim() + '/playwright'); }
const APP = pathToFileURL(path.join(__dirname, '..', 'index.html')).href;
const SAMPLE_CSV = path.join(__dirname, '..', 'sample', 'sample-vocabulary.csv');
const TXT = pathToFileURL(path.join(__dirname, '..', 'sample', 'sample-vocabulary.txt')).href;
const OUT = require('os').tmpdir();
const { chromium } = playwright;
const assert = (c, m) => { if (!c) { console.error('FAIL:', m); process.exitCode = 1; } else console.log('ok  -', m); };
(async () => {
  const b = await chromium.launch(); const page = await (await b.newContext({ viewport: { width: 1280, height: 800 }, locale: 'ru-RU' })).newPage();
  const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => m.type() === 'error' && errs.push(m.text()));
  await page.goto(APP);
  await page.waitForSelector('.empty');
  assert(await page.locator('h1').innerText() === 'Добро пожаловать в Lexi', 'auto-detected Russian from browser');
  assert(await page.evaluate(() => document.documentElement.lang) === 'ru', 'html lang=ru');
  await page.click('text=Загрузить пример словаря'); await page.waitForSelector('.stat-grid');
  await page.selectOption('#lang-select', 'uz');
  assert(await page.locator('nav a[data-route=vocabulary]').innerText() === "Mening lug'atim", 'nav in Uzbek');
  assert((await page.locator('h1').innerText()) === 'Bosh sahifa', 'dashboard re-rendered in Uzbek');
  await page.screenshot({ path: path.join(OUT, 'lexi-uz-dash.png') });
  await page.selectOption('#lang-select', 'en');
  await page.click('nav a[data-route=vocabulary]');
  assert((await page.locator('#v-count').innerText()) === '60 words in 5 collections', 'English plural: ' + await page.locator('#v-count').innerText());
  await page.selectOption('#lang-select', 'ru');
  assert((await page.locator('#v-count').innerText()).startsWith('60 слов'), 'ru plural: ' + await page.locator('#v-count').innerText());
  await page.click('nav a[data-route=practice]'); await page.selectOption('#s-len', '10'); await page.click('#setup .btn-primary');
  await page.fill('#answer', 'zzz'); await page.press('#answer', 'Enter'); await page.waitForSelector('#btn-next');
  console.log((await page.locator('.fb').innerText()).replace(/\n/g, ' | '));
  await page.screenshot({ path: path.join(OUT, 'lexi-ru-quiz.png') });
  await page.click('#btn-end'); await page.waitForSelector('.summary');
  await page.click('nav a[data-route=progress]'); await page.waitForSelector('.chart');
  await page.screenshot({ path: path.join(OUT, 'lexi-ru-progress.png'), fullPage: true });
  await page.click('nav a[data-route=settings]'); await page.click('label:has-text("Oʻzbekcha"), label:has-text("O\'zbekcha")');
  assert(await page.locator('h1').innerText() === 'Sozlamalar', 'settings language radio switches UI');
  await page.reload(); await page.waitForSelector('h1');
  assert(await page.locator('h1').innerText() === 'Sozlamalar', 'language persists after reload');
  await page.setViewportSize({ width: 390, height: 800 });
  await page.screenshot({ path: path.join(OUT, 'lexi-uz-mobile.png') });
  await page.click('nav a[data-route=vocabulary]'); await page.click('[data-action=import]');
  await page.fill('#imp-text', 'bad line\napple — olma'); await page.waitForTimeout(150);
  console.log((await page.locator('#imp-preview').innerText()).replace(/\n/g, ' | '));
  assert(errs.length === 0, 'no errors ' + errs.join(';'));
  await b.close();
})();
